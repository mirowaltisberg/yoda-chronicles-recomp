#!/bin/sh
# Assembles build/xcode, the equivalent of the Xcode project Unity 4.6.6's editor exports for an iOS
# IL2CPP build, from the extracted installer and this repository:
#
#   Classes/            Unity's Trampoline sources, pristine copy + ios/trampoline/*.ed (our changes only)
#   Classes/Register*   the files the editor generates (all engine classes registered, i.e. no stripping)
#   Libraries/          libil2cpp headers (engine and GNU libstdc++ variants live in build/engine)
#
# The IL2CPP output (build/il2cppOutput) and the data (build/Data) are referenced in place.
# Usage: tools/make_xcode.sh   (prepares both the Simulator and the iPhone library variants)
set -e
ROOT=$(cd "$(dirname "$0")/.." && pwd)
IOS="$ROOT/build/unity-4.6.6/pkg/Unity.pkg/Payload/Unity/Unity.app/Contents/PlaybackEngines/iossupport"
E="$ROOT/build/engine"
X="$ROOT/build/xcode"

[ -f "$E/libiPhone-lib-il2cpp-arm64.a" ] || lipo "$IOS/Trampoline/Libraries/libiPhone-lib-il2cpp.a" -thin arm64 -output "$E/libiPhone-lib-il2cpp-arm64.a"
for p in iossim ios; do [ -f "$E/libgnustdcxx-$p.a" ] || "$ROOT/tools/make_gnustdcxx.sh" "$p"; done
# A few 2015 objects say "iOS device"; untagged like the rest, the Simulator link accepts them.
[ -f "$E/libiPhone-lib-il2cpp-arm64-sim.a" ] || {
    "$ROOT/tools/.venv/bin/python" -I "$ROOT/tools/arsim.py" "$E/libiPhone-lib-il2cpp-arm64.a" "$E/libiPhone-lib-il2cpp-arm64-sim.a"
    ranlib "$E/libiPhone-lib-il2cpp-arm64-sim.a"
}

rm -rf "$X/Classes" "$X/Libraries"
mkdir -p "$X/Libraries"
cp -R "$IOS/Trampoline/Classes" "$X/Classes"
if [ -s "$ROOT/ios/trampoline/MANIFEST" ]; then
    # ed scripts from tools/save_trampoline_patch.sh; each applies only to the exact Unity 4.6.6 original
    while read -r sha f; do
        actual=$(shasum -a 256 "$X/Classes/$f" | cut -d' ' -f1)
        [ "$actual" = "$sha" ] || { echo "$f is not Unity 4.6.6's original (sha256 $actual)"; exit 1; }
        ed -s "$X/Classes/$f" < "$ROOT/ios/trampoline/$f.ed"
    done < "$ROOT/ios/trampoline/MANIFEST"
fi
cp -R "$IOS/il2cpp/libil2cpp" "$X/Libraries/libil2cpp"

# App icon: the original App Store artwork from the user's IPA (512x512, 2013), upscaled to the single
# 1024x1024 icon iOS wants now. Generated here, never committed.
ICON_SRC="$ROOT/input/x/ipa/iTunesArtwork"
ICONSET="$X/Assets.xcassets/AppIcon.appiconset"
rm -rf "$X/Assets.xcassets" && mkdir -p "$ICONSET"
printf '{"info":{"author":"xcode","version":1}}\n' > "$X/Assets.xcassets/Contents.json"
if [ -f "$ICON_SRC" ]; then
    "$ROOT/tools/.venv/bin/python" -I -c "import sys; from PIL import Image; Image.open(sys.argv[1]).convert('RGB').resize((1024, 1024), Image.LANCZOS).save(sys.argv[2])" \
        "$ICON_SRC" "$ICONSET/AppIcon-1024.png"
    printf '{"images":[{"filename":"AppIcon-1024.png","idiom":"universal","platform":"ios","size":"1024x1024"}],"info":{"author":"xcode","version":1}}\n' > "$ICONSET/Contents.json"
else
    printf '{"images":[{"idiom":"universal","platform":"ios","size":"1024x1024"}],"info":{"author":"xcode","version":1}}\n' > "$ICONSET/Contents.json"
fi

# RegisterClasses.cpp: every class the engine library contains (the editor lists the used ones when stripping)
{
    echo "// Generated by tools/make_xcode.sh: registers every native class of the engine library."
    echo "void RegisterAllClasses()"
    echo "{"
    nm -g --defined-only "$E/libiPhone-lib-il2cpp-arm64.a" 2>/dev/null \
        | awk '$3 ~ /^__Z[0-9]+RegisterClass_[A-Za-z0-9_]+v$/ {print $3}' | sort -u \
        | sed -E 's/^__Z[0-9]+RegisterClass_(.*)v$/\1/' \
        | while read -r c; do printf '\tvoid RegisterClass_%s(); RegisterClass_%s();\n' "$c" "$c"; done
    echo "}"
} > "$X/Classes/RegisterClasses.cpp"

# IL2CPP has no Mono AOT modules and the game has no [DllImport("__Internal")] functions.
printf '#pragma once\nvoid RegisterMonoModules();\n' > "$X/Classes/RegisterMonoModules.h"
printf '#include "RegisterMonoModules.h"\nvoid RegisterMonoModules() {}\n' > "$X/Classes/RegisterMonoModules.cpp"
# The game does not use UnityEngine.Gyroscope.
printf '#pragma once\nvoid RegisterFeatures();\n' > "$X/Classes/RegisterFeatures.h"
printf '#include "RegisterFeatures.h"\nextern bool gEnableGyroscope;\nvoid RegisterFeatures() { gEnableGyroscope = false; }\n' > "$X/Classes/RegisterFeatures.cpp"

echo "build/xcode ready: $(grep -c RegisterClass_ "$X/Classes/RegisterClasses.cpp") classes registered"
